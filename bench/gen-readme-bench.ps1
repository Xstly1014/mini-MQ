# M6: generate the README benchmark section from raw result JSONL / Kafka txt.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File bench/gen-readme-bench.ps1
#   powershell ... -OutFile docs/benchmarks/README-bench.md
#
# Rules (M6 DoD "README bench table is generated from JSONL, no hand-copying"):
#   - medians are recomputed from the `samples` field (3 raw rounds per row),
#     NOT trusted from the pre-computed throughputMsgSec/p99Ms columns;
#   - Kafka numbers come from the raw kafka-rf3-round*.txt lines;
#   - every row carries a caliber note and the evidence file it came from.
#   - NOTE: keep this file pure ASCII; PS 5.1 without BOM misreads UTF-8.
#     In double-quoted strings a literal backtick must be doubled (``).

param(
    [string]$OutFile = "",
    [string]$Root = ""
)

$ErrorActionPreference = "Stop"
if (-not $Root) { $Root = Split-Path -Parent (Split-Path -Parent $PSCommandPath) }

function Get-Median {
    param([double[]]$v)
    $s = $v | Sort-Object
    if ($s.Count -eq 0) { throw "median of empty" }
    if ($s.Count % 2 -eq 1) { return [double]$s[[int](($s.Count - 1) / 2)] }
    return ([double]$s[$s.Count / 2 - 1] + [double]$s[$s.Count / 2]) / 2.0
}

# Parse one benchmark jsonl row set: recompute throughput/p50/p99 medians from samples.
# samples format: "tp,p50,p95,p99,p999,cpu,heap;round2;round3"
function Read-BenchRow {
    param([string]$path)
    $rows = @()
    foreach ($line in (Get-Content $path)) {
        if (-not $line.Trim()) { continue }
        $o = $line | ConvertFrom-Json
        $tps = @(); $p99s = @(); $p50s = @()
        foreach ($r in ($o.samples -split ';')) {
            $f = $r.Split(',')
            $tps += [double]$f[0]
            $p50s += [double]$f[1]
            $p99s += [double]$f[3]
        }
        $rows += [pscustomobject]@{
            concurrency = $o.concurrency
            tp          = Get-Median $tps
            p50         = Get-Median $p50s
            p99         = Get-Median $p99s
            mode        = $o.mode
            readMode    = $o.readMode
            latencyKind = $o.latencyKind
            consumed    = $o.consumed
            messages    = $o.messages
        }
    }
    return $rows
}

function Best-By-Throughput {
    param($rows)
    return ($rows | Sort-Object tp -Descending)[0]
}

function Fmt([double]$x) { return ([math]::Round($x)).ToString("N0") }
function FmtLat([double]$x) {
    if ($x -lt 10) { return ([math]::Round($x, 2)).ToString("0.00") }
    return ([math]::Round($x)).ToString("N0")
}

$verified = Join-Path $Root "result/m5-20261017-verified"
$wsl      = Join-Path $Root "result/m5-20261017-rf3-wsl"

$produceWin   = Read-BenchRow (Join-Path $verified "produce.jsonl")
$consumeTail  = Read-BenchRow (Join-Path $verified "consume-tail.jsonl")
$consumeCold  = Read-BenchRow (Join-Path $verified "consume-cold.jsonl")
$clusterRf3   = Read-BenchRow (Join-Path $wsl "minimq-wsl-cluster-rf3-os.jsonl")
$produceOsWsl = Read-BenchRow (Join-Path $wsl "minimq-wsl-produce-os.jsonl")

# ---- Kafka raw rounds ----
$kafkaTp = @(); $kafkaP99 = @()
foreach ($f in @("kafka-rf3-round1.txt", "kafka-rf3-round2.txt", "kafka-rf3-round3.txt")) {
    foreach ($line in (Get-Content (Join-Path $wsl $f))) {
        if ($line -match '^600000 records sent, ([\d.]+) records/sec.* (\d+) ms 50th, (\d+) ms 95th, (\d+) ms 99th') {
            $kafkaTp  += [double]$Matches[1]
            $kafkaP99 += [double]$Matches[4]
        }
    }
}
if ($kafkaTp.Count -ne 3) { throw "expected 3 Kafka rounds, got $($kafkaTp.Count)" }
$kafkaTpMed  = Get-Median $kafkaTp
$kafkaP99Med = Get-Median $kafkaP99

# ---- headline rows ----
$pw = Best-By-Throughput $produceWin     # SYNC single broker (Windows)
$ct = Best-By-Throughput $consumeTail
$cc = Best-By-Throughput $consumeCold
$po = Best-By-Throughput $produceOsWsl   # OS single broker (WSL2)
$rf = Best-By-Throughput $clusterRf3     # RF=3 end-to-end

$tpRatio  = [math]::Round(100.0 * $rf.tp / $kafkaTpMed)
$p99Ratio = [math]::Round($rf.p99 / $kafkaP99Med, 2)

