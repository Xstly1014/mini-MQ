[void]$sb.AppendLine("| Single broker produce, OS_FLUSH | $(Fmt $po.tp) msg/s | $(FmtLat $po.p99) ms | WSL2, best conc $($po.concurrency); ``result/m5-20261017-rf3-wsl/minimq-wsl-produce-os.jsonl`` |")
