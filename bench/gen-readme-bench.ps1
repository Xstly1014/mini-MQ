[void]$sb.AppendLine("| Cold consume (broker restart, page cache NOT dropped) | $(Fmt $cc.tp) msg/s | $(FmtLat $cc.p99) ms | consume poll, conc $($cc.concurrency); ``result/m5-20261017-verified/consume-cold.jsonl`` |")
[void]$sb.AppendLine("| **3-node RF=3 end-to-end (acks=all)** | **$(Fmt $rf.tp) msg/s** | **$(FmtLat $rf.p99) ms** | WSL2, best conc $($rf.concurrency); ``result/m5-20261017-rf3-wsl/minimq-wsl-cluster-rf3-os.jsonl`` |")
[void]$sb.AppendLine("| Kafka 4.1.2 KRaft, same host & workload | $(Fmt $kafkaTpMed) msg/s | $(FmtLat $kafkaP99Med) ms | RF=3 acks=all, median of 3; ``result/m5-20261017-rf3-wsl/kafka-rf3-round*.txt`` |")
[void]$sb.AppendLine("| **mini-MQ / Kafka ratio** | **$tpRatio%** | **$($p99Ratio)x** | same WSL2 host, RF=3, acks=all, 1 KB; four-bucket attribution in ``docs/tuning.md`` |")
