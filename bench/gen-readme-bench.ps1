[void]$sb.AppendLine('<!-- GENERATED by bench/gen-readme-bench.ps1 from result/ JSONL + Kafka txt -- do not hand-edit numbers -->')
[void]$sb.AppendLine('## Benchmarks')
[void]$sb.AppendLine('')
